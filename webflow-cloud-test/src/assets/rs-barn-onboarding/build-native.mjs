import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const directory = fileURLToPath(new URL('.', import.meta.url));
const output = new URL('./native-client.js', import.meta.url);
const result = await build({
  absWorkingDir: directory, entryPoints: ['native.ts'], bundle: true,
  format: 'esm', platform: 'browser', target: 'es2022', write: false,
  banner: { js: '// Generated by build-native.mjs. Edit native.ts and the native adapter modules.' }
});
const content = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== content) throw new Error('native_barn_bundle_stale');
  console.log('PASS: native Barn bundle matches source and existing API');
} else await writeFile(output, content);
